/** Все статьи подряд — в порядке оглавления. По нему же работает «Дальше». */
export const ARTICLES: GuideArticle[] = GUIDE.flatMap((section) => section.articles)

export function findArticle(id: string): { article: GuideArticle; section: GuideSection } | null {
  for (const section of GUIDE) {
    const article = section.articles.find((a) => a.id === id)
    if (article) return { article, section }
  }
  return null
}

export function nextArticle(id: string): GuideArticle | null {
  const index = ARTICLES.findIndex((a) => a.id === id)
  return index >= 0 ? ARTICLES[index + 1] ?? null : null
}
