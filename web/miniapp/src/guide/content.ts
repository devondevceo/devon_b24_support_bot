/**
 * Инструкция по боту и мини-аппу — данными, а не вёрсткой.
 *
 * Данными по трём причинам. Поиск ходит по тем же строкам, что видит человек.
 * Экран один на все статьи, и выглядят они одинаково. И главное — текст можно
 * сверить с кодом: `tests/test_guide.py` читает этот файл как текст.
 *
 * Разметка внутри строк — четыре вида, и только они:
 *
 *   `код`             команда или то, что набирают руками: `/time 233 1ч30м`;
 *   [[кнопка бота]]   подпись кнопки бота ДОСЛОВНО, с эмодзи — как в чате;
 *   {{элемент}}       кнопка или поле приложения, {{подпись|значок}} — со значком;
 *   **важное**        выделение.
 *
 * Страж сверяет: каждая `/команда` есть в реестре бота (`bot/commands.py`), и
 * каждая команда реестра здесь названа; каждая [[кнопка бота]] дословно есть в
 * коде бота; каждый {{элемент}} — в коде приложения; каждый значок — в наборе.
 * Инструкция — то же обещание, что меню команд: переименовали кнопку — упадёт
 * тест, а не соврёт инструкция.
 *
 * Эмодзи здесь живут только внутри [[…]] и в легенде статусов: это цитаты того,
 * что человек видит в чате, а не значки интерфейса (docs/55-miniapp-design.md §8).
 */
import type { IconName } from '../ui/Icon'

export type GuideBlock =
  | { kind: 'p'; text: string }
  /** Подзаголовок: начинает новую карточку статьи. */
  | { kind: 'h'; text: string }
  | { kind: 'steps'; items: string[] }
  | { kind: 'list'; items: string[] }
  /** Термин и объяснение: команды, кнопки, сообщения бота. */
  | { kind: 'defs'; items: [string, string][] }
  /** Значок из сообщений бота и его смысл. Значок скринридеру не читается. */
  | { kind: 'legend'; items: [string, string][] }
  | { kind: 'note'; tone: 'info' | 'warn'; text: string }

/** Раздел приложения, куда статья может отвести кнопкой в конце. */
export type GuideTarget = 'list' | 'create' | 'summary' | 'timesheet' | 'approvals' | 'about'

export type GuideArticle = {
  id: string
  icon: IconName
  title: string
  /** Строка под заголовком в оглавлении: о чём статья, в пять слов. */
  summary: string
  /** Слова, которыми это ищут, но которых нет в тексте. */
  keywords?: string[]
  blocks: GuideBlock[]
  go?: { to: GuideTarget; label: string }
}

export type GuideSection = { id: string; title: string; articles: GuideArticle[] }

