"""Реестр пространств имён callback-кнопок.

В `callback_data` уходит только `<ns>:<token>` (docs/30-bot-spec.md §0.2): префикс
`ns` выбирает ветку в `handlers.on_callback`, а `token` разрешается в таблице
`callback_tokens`, где у каждого токена записан свой `kind`.

Реестр один на обе стороны — как `commands.py` для слеш-команд. Кнопка собирается
только через `data()`, поэтому «префикс, который бот шлёт» — это ровно первый
аргумент `data()`, и `tests/test_callbacks.py` сверяет реестр с эмиттерами и
с роутером по исходнику.

**Зачем реестр понадобился.** Префикс `p` успел означать сразу две вещи: вариант
ответа опросника и выбор проекта при создании задачи. Роутер разбирал первое,
вторая ветка стояла ниже и была недостижима — а человек в чате с двумя проектами
жал «создать» и получал «диалог устарел» вместо задачи. Ошибка молчаливая с обеих
сторон: эмиттер выдавал валидную кнопку, роутер честно отрабатывал первую ветку.

**Префикс объявляет, токены какого вида вправе под ним приехать, и это
проверяется на каждом нажатии.** Иначе токен одного вида можно отправить под
чужим префиксом и попасть в ветку, которая ждёт другой `payload`: токены меню,
например, выдаются без `owner_tg_id` и многоразовыми, то есть доступны любому
участнику чата.

Видов у префикса обычно один, но не всегда: кнопки под уведомлением носят общий
вид `notify` (`domain/events.py`) и расходятся по четырём префиксам — карточка,
обсуждение, действие, правка. Набор видов на префикс это описывает честно, а
жёсткая пара «один к одному» потребовала бы плодить виды токенов ради формы.
"""
from __future__ import annotations

from dataclasses import dataclass

# Вид токена кнопок под уведомлением. Уведомление приходит само, кнопка у него
# без владельца, а смысл нажатия задаёт `payload`, а не префикс — поэтому один вид
# на все четыре префикса (keyboards.NOTIFY_BUTTONS, domain/events.NOTIFY_PAYLOAD).
NOTIFY = "notify"


@dataclass(frozen=True)
class Namespace:
    ns: str                  # префикс в callback_data
    kinds: tuple[str, ...]   # виды токенов, которые вправе приехать под этим префиксом
    purpose: str             # что делает кнопка — для доков и разбора логов


# Порядок — как в роутере: опросник, создание задачи, задачи, администрирование.
NAMESPACES: tuple[Namespace, ...] = (
    Namespace("s", ("survey",), "выбор категории обращения"),
    Namespace("p", ("survey_pick",), "вариант ответа на вопрос опросника"),
    Namespace("k", ("survey_skip",), "пропуск необязательного вопроса"),
    Namespace("x", ("survey_cancel",), "отмена опросника"),
    Namespace("c", ("survey_create",), "создание задачи по собранным ответам"),
    Namespace("tp", ("task:project",), "выбор проекта при создании задачи из сообщения"),
    Namespace("m", ("menu",), "меню чата: сводка, списки, трудозатраты, возврат"),
    # Личка: ChatContext там взять неоткуда (личных чатов нет в tg_chats), поэтому
    # у отчёта свой префикс и своя ветка ДО загрузки контекста — как у `av`.
    Namespace("mt", ("timesheet",), "трудозатраты в личке: выбор месяца и отчёт"),
    Namespace("t", ("task", NOTIFY), "открыть карточку задачи"),
    Namespace("d", (NOTIFY,), "показать обсуждение задачи"),
    Namespace("a", ("action", NOTIFY), "действие в карточке: завершить, в работу, пауза"),
    Namespace("e", ("edit", NOTIFY), "изменение срока, ответственного, приоритета, стадии"),
    # Своё пространство, а не пункт внутри `e`: списание времени не меняет полей
    # задачи, пишется другим методом портала и другим именем в аудите. Общий
    # префикс означал бы, что «одно действие» из реестра — это на самом деле два.
    Namespace("tl", ("timelog",), "списание времени: экран задачи и быстрые кнопки"),
    # Личка: то же списание, но своя ветка ДО загрузки контекста и свой вид
    # токена — как у `mt` и `av`. Общий вид означал бы, что кнопку из чата можно
    # отправить в ветку, которая проверяет права по теннанту, а не по привязке
    # чата, и наоборот; проверка при этом выглядела бы выполненной.
    Namespace("tm", ("timelog_dm",),
              "списание времени в личке: выбор задачи и быстрые кнопки"),
    Namespace("b", ("admin:bind",), "привязка и отвязка проекта к чату"),
    Namespace("av", ("task_approval",), "решение ответственного по новой задаче"),
    Namespace("dg", ("digest",), "включение и выключение утренней сводки в чате"),
)

BY_NS: dict[str, Namespace] = {n.ns: n for n in NAMESPACES}


def data(ns: str, token: str) -> str:
    """Единственное место, где собирается `callback_data`.

    Незарегистрированный префикс — это кнопка, которую роутер не разберёт.
    Падаем здесь и сразу: дешевле, чем мёртвая кнопка в чате у человека.
    """
    if ns not in BY_NS:
        raise ValueError(f"пространство имён {ns!r} не объявлено в callbacks.NAMESPACES")
    return f"{ns}:{token}"


def accepts(ns: str, kind: str) -> bool:
    """Вправе ли токен такого вида приехать под этим префиксом.

    Незарегистрированный префикс не принимает ничего: разбирать его всё равно
    некому, а молчаливое «ну ладно» здесь означало бы ветку наугад.
    """
    entry = BY_NS.get(ns)
    return entry is not None and kind in entry.kinds
